const test = require('node:test')
const assert = require('node:assert/strict')
const hall = require('../services/hall.service')

test('vào sảnh ẩn danh nhận nệm gần nhất, vào lặp không chiếm thêm nệm', () => {
  const s = hall.createStore()
  hall.join(s, 'a', 'chung', '', 0, { x: 8, z: 6 })
  const first = hall.state(s, 'chung', 0)
  assert.equal(first.capacity, 100)
  assert.equal(first.count, 1)
  assert.equal(first.people[0].cushionId, 99)
  assert.equal(first.people[0].pose, 'standing')
  assert.match(first.people[0].name, /^Khách /)
  hall.join(s, 'a', 'chung', 'An', 1)
  assert.equal(hall.state(s, 'chung', 1).count, 1)
  assert.equal(hall.state(s, 'chung', 1).occupied, 1)
})

test('100 nệm độc quyền, hàng đợi FIFO; nhả, rời và đổi phòng đều cấp lại đúng người', () => {
  const s = hall.createStore()
  for (let i = 0; i < 103; i++) hall.join(s, `s${i}`, 'chung', 'Khách', i)
  let state = hall.state(s, 'chung', 200)
  assert.equal(state.occupied, 100)
  assert.equal(state.waiting, 3)
  assert.equal(new Set(state.people.slice(0, 100).map((p) => p.cushionId)).size, 100)
  hall.leave(s, 's101')
  hall.release(s, 's0', 300)
  assert.equal(hall.people(s, 'chung').find((p) => p.id === s.seats.get('s100').id).waiting, false)
  hall.join(s, 's1', 'khac', 'An', 400)
  assert.equal(s.seats.get('s102').waiting, false)
  hall.join(s, 's103', 'chung', 'Khách', 450)
  hall.claim(s, 's0', 500)
  assert.equal(s.seats.get('s0').waiting, true)
  hall.leave(s, 's2')
  assert.equal(s.seats.get('s103').waiting, false)
  assert.equal(s.seats.get('s0').waiting, true)
  hall.leave(s, 's3')
  assert.equal(s.seats.get('s0').waiting, false)
  assert.equal(hall.leave(s, 'khong-co'), null)
  for (const id of [...s.seats.keys()]) hall.leave(s, id)
  assert.equal(s.rooms.size, 0)
  assert.equal(s.seats.size, 0)
  assert.equal(s.limits.size, 0)
})

test('di chuyển tối đa 10Hz, chặn tọa độ lỗi, vượt biên, tăng tốc và không cho giả tư thế', () => {
  const s = hall.createStore()
  hall.join(s, 'a', 'chung', 'An', 0)
  assert.equal(hall.move(s, 'a', { x: 0.2, z: 10, rotation: 1, pose: 'bowing', cushionId: 0 }, 100), 'chung')
  for (let i = 0; i < 100; i++) assert.equal(hall.move(s, 'a', { x: 0.4, z: 10 }, 100), null)
  assert.equal(hall.move(s, 'a', { x: 30, z: 10 }, 200), null)
  assert.equal(hall.move(s, 'a', { x: NaN, z: 10 }, 200), null)
  assert.equal(hall.move(s, 'a', { x: 0, z: Infinity }, 200), null)
  assert.equal(hall.move(s, 'a', { x: '0', z: 10 }, 200), null)
  assert.equal(hall.move(s, 'a', null, 200), null)
  assert.equal(hall.move(s, 'a', { x: 31, z: 10 }, 200), null)
  const p = hall.people(s, 'chung')[0]
  assert.equal(p.x, 0.2)
  assert.equal(p.pose, 'standing')
  assert.notEqual(p.cushionId, 0)
  assert.equal(hall.move(s, 'a', { x: 0.4, z: 10 }, 200), 'chung')
})

test('tư thế do server giữ, chắp tay hết sau 1 giây, đóng tràng hạt khôi phục quỳ', () => {
  const s = hall.createStore()
  hall.join(s, 'a', 'chung', 'An', 0, { x: 7.2, z: 6.3 })
  assert.equal(hall.pose(s, 'a', 'kneeling', 100), 'chung')
  hall.pose(s, 'a', 'beads', 200)
  for (let i = 0; i < 110; i++) hall.bead(s, 'a', 200 + i * 100)
  assert.equal(hall.people(s, 'chung')[0].beads, 110)
  assert.equal(hall.bead(s, 'a', 11101), null)
  hall.pose(s, 'a', 'restore', 12000)
  assert.equal(hall.people(s, 'chung')[0].pose, 'kneeling')
  hall.pose(s, 'a', 'praying', 12100)
  hall.tick(s, 13099)
  assert.equal(hall.people(s, 'chung')[0].pose, 'praying')
  hall.tick(s, 13100)
  assert.equal(hall.people(s, 'chung')[0].pose, 'kneeling')
  hall.pose(s, 'a', 'bowing', 14000)
  assert.equal(hall.people(s, 'chung')[0].pose, 'bowing')
  assert.equal(hall.move(s, 'a', { x: 7.3, z: 6.3 }, 15000), null)
  hall.pose(s, 'a', 'standing', 15000)
  assert.equal(hall.people(s, 'chung')[0].pose, 'standing')
  assert.equal(hall.pose(s, 'a', 'fake', 16000), null)
  hall.release(s, 'a', 17000)
  assert.equal(hall.pose(s, 'a', 'kneeling', 18000), null)
  assert.equal(hall.pose(s, 'unknown', 'praying', 0), null)
})

